/** Preço para o inglês: "35€/mês" → "€35/month", "350€" → "€350". */
export function priceFor(lang: Lang, price: string) {
  if (lang === "pt") return price
  return price.replace(/^(\d+)€\/mês$/, "€$1/month").replace(/^(\d+)€$/, "€$1")
}
