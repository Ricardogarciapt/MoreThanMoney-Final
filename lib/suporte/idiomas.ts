/** Os textos do apoio no idioma pedido (qualquer variante: «en-US», «zh»…); o que faltar cai para PT. */
export function textosApoio(idioma: string | null | undefined): TextosApoio {
  return TEXTOS_APOIO[normalizeLang(idioma)] ?? TEXTOS_APOIO.pt
}

/** Só aceita um dos 21 idiomas; o resto (ou nada) vira PT. Para gravar na conversa. */
export function idiomaApoio(v: unknown): Lang {
  return typeof v === 'string' ? normalizeLang(v) : 'pt'
}

export const IDIOMAS_APOIO: readonly Lang[] = I18N_LANGS
